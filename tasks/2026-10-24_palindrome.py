"""
Задача дня — 2026-10-24
Тема: строки · Уровень: лёгкая

Палиндром

Напишите функцию is_palindrome(text), которая возвращает True, если строка
читается одинаково слева направо и справа налево. Регистр, пробелы и знаки
препинания не учитываются.

Примеры:
    is_palindrome("А роза упала на лапу Азора")  -> True
    is_palindrome("Привет")                       -> False
"""


def is_palindrome(text: str) -> bool:
    # Оставляем только буквы и цифры и приводим их к нижнему регистру
    cleaned = [ch.lower() for ch in text if ch.isalnum()]
    # Строка — палиндром, если совпадает со своим разворотом
    return cleaned == cleaned[::-1]


# Как это работает:
# 1. str.isalnum() отбрасывает пробелы и знаки препинания, str.lower() убирает
#    разницу между «А» и «а».
# 2. Срез [::-1] возвращает последовательность задом наперёд.
# 3. Сложность — O(n) по времени и по памяти.
#
# Попробуйте сами: решите задачу без лишней памяти, двигая два указателя
# навстречу друг другу с концов строки.


if __name__ == "__main__":
    assert is_palindrome("А роза упала на лапу Азора")
    assert is_palindrome("Was it a car or a cat I saw?")
    assert is_palindrome("12321")
    assert is_palindrome("")
    assert not is_palindrome("Привет")
    assert not is_palindrome("ab")
    print("Все проверки пройдены ✅")
